"""The Vulkan engine's shaders, compiled to SPIR-V and embedded in one header
(shaders_spv.h), as fast/scripts/build_vmaf_vulkan.ps1 makes it on Windows,
for the other systems' builds (build_vmaf_vulkan_macos.sh).

The shaders, their definitions and their order are read from
build_vmaf_vulkan.ps1's $shaders table, so that there is one list; the
NoContraction decorations are added as its Add-NoContraction adds them.

    python3 build_vmaf_vulkan_shaders.py SLANGC OUTPUT_FOLDER [DEFINITION ...]

The definitions after the folder are given to every shader (the macOS
build's WAVE_INT64=0).
"""
from __future__ import annotations

import re
import struct
import subprocess
import sys
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
SOURCE = SCRIPTS.parent / "vulkan"


def shader_table() -> list[tuple[str, str, list[str]]]:
    """build_vmaf_vulkan.ps1's $shaders, in order: (name, file, definitions)."""
    text = (SCRIPTS / "build_vmaf_vulkan.ps1").read_text(encoding="utf-8")
    start = text.index("$shaders = [ordered]@{")
    end = text.index("\n}\n", start)
    table = []
    for line in text[start:end].splitlines()[1:]:
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        match = re.fullmatch(r"'([^']+)'\s*=\s*(.+)", line)
        if not match:
            raise ValueError(f"an entry of the shader table not understood: {line!r}")
        values = re.findall(r"'([^']*)'", match.group(2))
        table.append((match.group(1), values[0], values[1:]))
    if not table:
        raise ValueError("no shaders in build_vmaf_vulkan.ps1")
    return table


def add_no_contraction(spirv: bytes) -> bytes:
    """Every float multiply, add, subtract and negation decorated
    NoContraction (build_vmaf_vulkan.ps1's Add-NoContraction): the
    decorations before the module's first."""
    words = list(struct.unpack(f"<{len(spirv) // 4}I", spirv))
    if words[0] != 0x07230203:
        raise ValueError("not a SPIR-V module")
    ids = []
    first = -1
    i = 5
    while i < len(words):
        opcode = words[i] & 0xFFFF
        length = words[i] >> 16
        if length == 0 or i + length > len(words):
            raise ValueError("a malformed SPIR-V module")
        if first < 0 and opcode in (71, 72):  # OpDecorate, OpMemberDecorate
            first = i
        if opcode in (127, 129, 131, 133):  # OpFNegate, OpFAdd, OpFSub, OpFMul
            ids.append(words[i + 2])
        i += length
    if first < 0:
        raise ValueError("a SPIR-V module without decorations")
    decorations = []
    for result in ids:
        decorations += [0x00030047, result, 42]  # OpDecorate, 3 words; NoContraction
    patched = words[:first] + decorations + words[first:]
    return struct.pack(f"<{len(patched)}I", *patched)


def main() -> int:
    slangc, output, common = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3:]
    output.mkdir(parents=True, exist_ok=True)
    table = shader_table()
    lines = ["// Generated by fast/scripts/build_vmaf_vulkan_shaders.py from fast/vulkan/shaders.",
             "#include <stdint.h>", "#include <stddef.h>", ""]
    for name, file, definitions in table:
        spirv = output / f"{name}.spv"
        subprocess.run([str(slangc), str(SOURCE / "shaders" / f"{file}.slang"), "-target", "spirv", "-profile",
                        "spirv_1_3", "-entry", "main", "-stage", "compute", "-O2", "-o", str(spirv)]
                       + [f"-D{definition}" for definition in definitions + common], check=True)
        data = spirv.read_bytes()
        if "NO_CONTRACTION=1" in definitions:
            data = add_no_contraction(data)
        words = [f"0x{word:08x}" for word in struct.unpack(f"<{len(data) // 4}I", data)]
        lines.append(f"static const uint32_t kSpirv_{name}[] = {{")
        for i in range(0, len(words), 10):
            lines.append("    " + ", ".join(words[i:i + 10]) + ",")
        lines += ["};", ""]
    lines.append("enum {")
    lines += [f"    kShader_{name}," for name, _, _ in table]
    lines += ["    kShaderCount", "};", ""]
    lines.append("static const struct { const char *name; const uint32_t *code; size_t bytes; } "
                 "kShaders[kShaderCount] = {")
    lines += [f'    {{ "{name}", kSpirv_{name}, sizeof kSpirv_{name} }},' for name, _, _ in table]
    lines.append("};")
    (output / "shaders_spv.h").write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"{len(table)} shaders in {output / 'shaders_spv.h'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
